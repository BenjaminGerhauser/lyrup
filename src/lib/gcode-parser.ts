export interface ParserDefaults {
  density: number
  diameter: number
}

const DEFAULT_DENSITY = 1.24 // g/cm³ — PLA
const DEFAULT_DIAMETER = 1.75 // mm

/**
 * Parse a G-code file content string and return extracted metadata.
 *
 * @param content  Full G-code file text
 * @param defaults Optional density/diameter overrides (fallback: PLA 1.24 g/cm³ / 1.75mm)
 * @returns GcodeData if the slicer is recognised, null otherwise
 */
export function parseGcode(content: string, defaults?: ParserDefaults): GcodeData | null {
  if (!content || content.trim().length === 0) return null

  // Slicer detection only needs the first ~200 lines: the `generated by …`
  // comment is always near the top of every supported slicer.
  const allLines = content.split(/\r?\n/)
  const headLines = allLines.length > 200 ? allLines.slice(0, 200) : allLines

  const detected = detectSlicer(headLines)
  if (!detected) return null

  // For metadata extraction we walk ALL lines (header for Cura/S3D, footer
  // for PrusaSlicer/Orca/Bambu). Each extractor short-circuits once every
  // critical field is filled, so a 50k-line file still parses in milliseconds.
  const lines = allLines

  const density = defaults?.density ?? DEFAULT_DENSITY
  const diameter = defaults?.diameter ?? DEFAULT_DIAMETER

  let partial: Partial<GcodeData>

  switch (detected.slicerType) {
    case 'cura':
      partial = extractCura(lines, diameter, density)
      break
    case 'prusaslicer':
      partial = extractPrusa(lines, diameter, density)
      break
    case 'orcaslicer':
      partial = extractOrca(lines, diameter, density)
      break
    case 'bambustudio':
      partial = extractBambu(lines, diameter, density)
      break
    case 'simplify3d':
      partial = extractSimplify3D(lines, diameter, density)
      break
    default:
      return null
  }

  return {
    slicerName: detected.slicerName,
    slicerType: detected.slicerType,
    estimatedTimeMinutes: partial.estimatedTimeMinutes ?? null,
    filamentUsedMm: partial.filamentUsedMm ?? null,
    filamentUsedGrams: partial.filamentUsedGrams ?? null,
    layerCount: partial.layerCount ?? null,
    nozzleTemp: partial.nozzleTemp ?? null,
    bedTemp: partial.bedTemp ?? null,
    printerIdentifier: partial.printerIdentifier ?? null,
    filamentType: partial.filamentType ?? null,
    filamentBrand: partial.filamentBrand ?? null,
  }
}
